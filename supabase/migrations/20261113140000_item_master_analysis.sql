-- Power BI Item Master Analysis mirror (Tally mst_stock_item + Swamiji Google Sheet).
-- Refreshed by /api/cron/item-master-analysis-sync every 8 hours.

CREATE TABLE IF NOT EXISTS public.item_master_analysis (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  row_key text NOT NULL,
  import_or_local text,
  main_group text,
  sub_group text,
  category text,
  tally_item_code text,
  tally_item_name text,
  google_article_no text,
  google_article_common_name text,
  brand_name text,
  tally_base_uom text,
  tally_alt_uom text,
  tally_alt_uom_conv numeric,
  synced_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT item_master_analysis_row_key_key UNIQUE (row_key)
);

COMMENT ON TABLE public.item_master_analysis IS
  'Joined Item Master Analysis rows from Power BI (Tally mst_stock_item + Google Sheet Item Master).';

CREATE INDEX IF NOT EXISTS idx_item_master_analysis_tally_code
  ON public.item_master_analysis (tally_item_code);

CREATE INDEX IF NOT EXISTS idx_item_master_analysis_article
  ON public.item_master_analysis (google_article_no);

CREATE INDEX IF NOT EXISTS idx_item_master_analysis_category
  ON public.item_master_analysis (category);

CREATE INDEX IF NOT EXISTS idx_item_master_analysis_synced_at
  ON public.item_master_analysis (synced_at DESC);

ALTER TABLE public.item_master_analysis ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated users can read item master analysis"
  ON public.item_master_analysis;
CREATE POLICY "Authenticated users can read item master analysis"
  ON public.item_master_analysis
  FOR SELECT
  TO authenticated
  USING (true);

GRANT SELECT ON TABLE public.item_master_analysis TO authenticated;
GRANT ALL ON TABLE public.item_master_analysis TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.item_master_analysis_id_seq TO service_role;
